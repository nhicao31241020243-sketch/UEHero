class _JobRow {
  const _JobRow(
    this.id,
    this.title,
    this.company,
    this.fieldId,
    this.skills,
    this.salary,
    this.salaryMin,
    this.location,
    this.mode,
    this.type,
    this.hoursAgo,
    this.description,
  );

  final String id;
  final String title;
  final String company;
  final String fieldId;
  final String skills;
  final String salary;
  final double salaryMin;
  final String location;
  final JobWorkMode mode;
  final JobType type;
  final int hoursAgo;
  final String description;
}

List<StudentJob> buildExtraDemoJobs() {
  final now = DateTime.now();
  return [
    for (final row in _rows)
      StudentJob(
        id: row.id,
        title: row.title,
        company: row.company,
        fieldId: row.fieldId,
        requiredSkills: _parseSkills(row.skills),
        salaryLabel: row.salary,
        salaryMin: row.salaryMin,
        location: row.location,
        workMode: row.mode,
        jobType: row.type,
        postedAt: now.subtract(Duration(hours: row.hoursAgo)),
        description: row.description,
        isDemo: true,
      ),
  ];
}

List<JobSkillRequirement> _parseSkills(String spec) => [
  for (final token in spec.split(' '))
    () {
      final parts = token.split(':');
      final entry = _skillCatalog[parts[0]]!;
      return JobSkillRequirement(
        skillKey: entry.$1,
        label: entry.$2,
        requiredLevel: int.parse(parts[1]),
      );
    }(),
];

